// A visible spinning indicator for in-flight async actions (auth
// transitions especially) — a disabled button with changed text alone
// wasn't a strong enough signal that something was happening; the gap
// between "clicked" and "next page appears" read as the site having
// frozen instead of just being mid-request/mid-navigation.
export function Spinner({ className = "" }: { className?: string }) {
  return (
    <svg
      className={`h-4 w-4 animate-spin ${className}`}
      viewBox="0 0 24 24"
      fill="none"
      aria-hidden="true"
    >
      <circle className="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" strokeWidth="3" />
      <path
        className="opacity-90"
        fill="currentColor"
        d="M4 12a8 8 0 0 1 8-8V0C5.373 0 0 5.373 0 12h4Z"
      />
    </svg>
  );
}
